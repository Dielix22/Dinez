-- Initial schema of the "Ticket management" module.
-- Source: docs/dev/design/02_Interaction_and_Data_Design_v2.md, sections 2.2 and 2.4.
--
-- Triage levels go from 1 to 5, but only levels 2 to 5 have a queue, a wait
-- limit and a daily counter (BR-TRG-03, REQ-10). Level 1 exists only as a
-- patient level.

CREATE TABLE triage_level (
    level smallint    NOT NULL,
    name  varchar(20) NOT NULL,
    CONSTRAINT pk_triage_level PRIMARY KEY (level),
    CONSTRAINT uq_triage_level_name UNIQUE (name),
    CONSTRAINT ck_triage_level_range CHECK (level BETWEEN 1 AND 5),
    CONSTRAINT ck_triage_level_name_not_blank CHECK (length(trim(name)) > 0)
);

-- Maximum wait time per level (REQ-10, REQ-11).
CREATE TABLE wait_limit (
    level         smallint NOT NULL,
    limit_minutes integer  NOT NULL,
    CONSTRAINT pk_wait_limit PRIMARY KEY (level),
    CONSTRAINT fk_wait_limit_triage_level FOREIGN KEY (level) REFERENCES triage_level (level),
    CONSTRAINT ck_wait_limit_level_range CHECK (level BETWEEN 2 AND 5),
    CONSTRAINT ck_wait_limit_minutes_positive CHECK (limit_minutes > 0)
);

-- The FIFO queue of a level. One row per level that has a queue.
CREATE TABLE level_queue (
    level smallint NOT NULL,
    CONSTRAINT pk_level_queue PRIMARY KEY (level),
    CONSTRAINT fk_level_queue_triage_level FOREIGN KEY (level) REFERENCES triage_level (level),
    CONSTRAINT ck_level_queue_level_range CHECK (level BETWEEN 2 AND 5)
);

-- Last ticket number issued for a level on a given day (CON-TRG-02).
CREATE TABLE ticket_counter (
    ticket_date   date     NOT NULL,
    level       smallint NOT NULL,
    last_number integer  NOT NULL,
    CONSTRAINT pk_ticket_counter PRIMARY KEY (ticket_date, level),
    CONSTRAINT fk_ticket_counter_triage_level FOREIGN KEY (level) REFERENCES triage_level (level),
    CONSTRAINT ck_ticket_counter_level_range CHECK (level BETWEEN 2 AND 5),
    CONSTRAINT ck_ticket_counter_last_number CHECK (last_number >= 0)
);

-- Only identification data is copied from Registration; clinical and other
-- demographic data are not stored here. `document` is deliberately not unique
-- (open question in section 5 of the design document).
CREATE TABLE patient (
    patient_id   varchar(50)  NOT NULL,
    document     varchar(50)  NOT NULL,
    first_name   varchar(100) NOT NULL,
    last_name    varchar(100) NOT NULL,
    triage_level smallint     NOT NULL,
    created_at   timestamp    NOT NULL,
    CONSTRAINT pk_patient PRIMARY KEY (patient_id),
    CONSTRAINT fk_patient_triage_level FOREIGN KEY (triage_level) REFERENCES triage_level (level),
    CONSTRAINT ck_patient_id_not_blank CHECK (length(trim(patient_id)) > 0),
    CONSTRAINT ck_patient_document_not_blank CHECK (length(trim(document)) > 0),
    CONSTRAINT ck_patient_first_name_not_blank CHECK (length(trim(first_name)) > 0),
    CONSTRAINT ck_patient_last_name_not_blank CHECK (length(trim(last_name)) > 0)
);

-- A ticket assigned to a patient for one visit, with its place in the queue.
-- `level` is the level in which the ticket waits or waited; it can differ from
-- patient.triage_level once the ticket is served. A served ticket keeps its row,
-- with `exit_time` filled in.
CREATE TABLE ticket (
    ticket_id      bigint      GENERATED BY DEFAULT AS IDENTITY,
    ticket_date    date        NOT NULL,
    ticket_number  varchar(20) NOT NULL,
    patient_id   varchar(50) NOT NULL,
    arrival_time timestamp   NOT NULL,
    level        smallint    NOT NULL,
    position     integer     NOT NULL,
    exit_time    timestamp,
    CONSTRAINT pk_ticket PRIMARY KEY (ticket_id),
    CONSTRAINT uq_ticket_date_number UNIQUE (ticket_date, ticket_number),
    CONSTRAINT fk_ticket_patient FOREIGN KEY (patient_id) REFERENCES patient (patient_id),
    CONSTRAINT fk_ticket_level_queue FOREIGN KEY (level) REFERENCES level_queue (level),
    CONSTRAINT ck_ticket_level_range CHECK (level BETWEEN 2 AND 5),
    CONSTRAINT ck_ticket_position_positive CHECK (position >= 1),
    CONSTRAINT ck_ticket_exit_not_before_arrival CHECK (exit_time IS NULL OR exit_time >= arrival_time)
);

-- A patient cannot have two waiting tickets (existePaciente).
CREATE UNIQUE INDEX uq_ticket_waiting_patient
    ON ticket (patient_id)
    WHERE exit_time IS NULL;

-- A position is unique within a level among the waiting tickets.
CREATE UNIQUE INDEX uq_ticket_waiting_level_position
    ON ticket (level, position)
    WHERE exit_time IS NULL;
